"""Generate `src/casefold.ts`: Unicode full case folding as a lookup table.

JavaScript has no case folding. `toLowerCase` is a different mapping: it
leaves `ß` alone where full folding gives `ss`, lowers `ẞ` to `ß` rather than
`ss`, and keeps final sigma distinct. A heading key folds case the way the
canonical implementation does, with Python's `str.casefold`, which applies the
`C` and `F` statuses of the Unicode Character Database's `CaseFolding.txt`.
This script asks that function about every code point and writes down every
one it changes, so the table is the canonical rule rather than a reading of
it, and regenerating it is how the table follows a new Unicode version.

    uv run python tools/hmd-ts-core/scripts/casefold.py
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "casefold.ts"


def main() -> None:
    entries = []
    for code in range(sys.maxunicode + 1):
        if 0xD800 <= code <= 0xDFFF:
            continue
        char = chr(code)
        folded = char.casefold()
        if folded != char:
            entries.append(f"{code:x}:" + " ".join(f"{ord(c):x}" for c in folded))

    lines = []
    line = ""
    for entry in entries:
        piece = entry + ";"
        if len(line) + len(piece) > 76:
            lines.append(line)
            line = ""
        line += piece
    if line:
        lines.append(line)
    body = "\n".join(f'  "{each}" +' for each in lines).rstrip(" +")

    OUT.write_text(
        f"""/**
 * Unicode full case folding, as a table — generated by
 * `scripts/casefold.py` from Python's `str.casefold` (Unicode
 * {unicodedata.unidata_version}), which applies the `C` and `F` statuses of
 * `CaseFolding.txt`. Do not edit by hand; regenerate it.
 *
 * Each entry is `code:folded`, hexadecimal, with a multi-character folding
 * written as code points separated by spaces.
 */

export const UNICODE_VERSION = "{unicodedata.unidata_version}";

export const CASE_FOLDING_TABLE =
{body};
""",
        encoding="utf-8",
    )
    print(f"{OUT}: {len(entries)} foldings, Unicode {unicodedata.unidata_version}")


if __name__ == "__main__":
    main()
